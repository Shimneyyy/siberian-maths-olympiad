import "dotenv/config";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { PrismaClient } from "@prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";
import { randomUUID } from "node:crypto";
import { after, test } from "node:test";
import assert from "node:assert/strict";
const exec = promisify(execFile);
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }) });
after(() => db.$disconnect());
test("bootstrap CLI is repeatable and cannot promote an existing student", async () => {
  const email = `bootstrap-${randomUUID()}@example.test`;
  const student = await db.user.create({ data: { email: `student-${randomUUID()}@example.test`, name: "Тестовый студент" } });
  const edition = await db.olympiadEdition.create({ data: { year: 6300, title: "Тест bootstrap" } });
  const invoke = (address: string) => exec(process.execPath, ["--import", "tsx", "scripts/bootstrap-admin.ts", address, "Синтетический главный организатор", edition.id]);
  try {
    await invoke(email);
    await invoke(email);
    const user = await db.user.findUniqueOrThrow({ where: { email }, include: { editionGrants: true, accounts: true } });
    assert.equal(user.role, "TECHNICAL_ADMIN");
    assert.equal(user.editionGrants.length, 0);
    assert.equal(user.accounts.length, 0, "No password is generated by bootstrap");
    await assert.rejects(invoke(student.email));
    await assert.rejects(invoke(`second-${randomUUID()}@example.test`));
    assert.equal((await db.user.findUniqueOrThrow({ where: { id: student.id } })).role, "STUDENT");
  } finally {
    const user = await db.user.findUnique({ where: { email } });
    await db.auditEvent.deleteMany({ where: { OR: [{ editionId: edition.id }, { objectId: user?.id ?? student.id }] } });
    await db.editionStaffGrant.deleteMany({ where: { editionId: edition.id } });
    await db.olympiadEdition.delete({ where: { id: edition.id } });
    await db.user.deleteMany({ where: { id: { in: [student.id, ...(user ? [user.id] : [])] } } });
  }
});
