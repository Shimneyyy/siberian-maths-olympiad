test("C11 only chief transfers active onsite participation, preserves snapshots/team/attendance and atomically enqueues one notice", async () => {
  const { transferParticipation } = await import("../src/lib/transfers");
  await db.rateLimit.deleteMany();
  const before = await db.participation.findUniqueOrThrow({ where: { userId_editionId: { userId: outsider, editionId: edition } } });
  const team = await db.team.create({ data: { editionId: edition, universityId: before.universityId, captainParticipationId: before.id, slot: 1, name: "УВ-1", coachName: "Учебный тренер" } });
  await db.teamMember.create({ data: { participationId: before.id, teamId: team.id, editionId: edition, universityId: before.universityId } });
  await db.attendance.create({ data: { participationId: before.id, status: "PRESENT", markedById: chief } });
  const staff = [];
  for (const venueId of [before.editionVenueId!,site]) {
    const user = await db.user.create({data:{name:"Учебный организатор переноса",email:`${randomUUID()}@example.test`,role:"VENUE_ORGANIZER",emailVerified:true}});
    await db.venueStaffAssignment.create({data:{userId:user.id,editionId:edition,editionVenueId:venueId}}); staff.push(user.id);
  }
  const { listRegistrations } = await import("../src/lib/registrations");
  assert.ok((await listRegistrations(db,staff[0],{editionId:edition})).rows.some(x=>x.id===before.id));
  const input = { editionId: edition, participationId: before.id, editionVenueId: site, revision: before.revision, reason: "Учебная причина переноса", confirmed: true, password };
  const results = await Promise.allSettled([transferParticipation(db, chief, input), transferParticipation(db, chief, input)]);
  assert.equal(results.filter(x => x.status === "fulfilled").length, 1);
  const after = await db.participation.findUniqueOrThrow({ where: { id: before.id } });
  assert.ok(!(await listRegistrations(db,staff[0],{editionId:edition})).rows.some(x=>x.id===before.id));
  assert.ok((await listRegistrations(db,staff[1],{editionId:edition})).rows.some(x=>x.id===before.id));
  assert.equal((await db.teamMember.findUniqueOrThrow({where:{participationId:before.id}})).teamId,team.id);
  assert.equal(after.editionVenueId, site); assert.equal(after.revision,before.revision+1);
  assert.deepEqual({ ...after, editionVenueId: before.editionVenueId, revision: before.revision }, before);
  assert.equal((await db.attendance.findUniqueOrThrow({where:{participationId:before.id}})).status,"PRESENT");
  const correction = await db.participationCorrection.findFirstOrThrow({where:{participationId:before.id}});
  assert.equal(correction.reason,input.reason);
  const event = await db.outboxEvent.findFirstOrThrow({where:{kind:"TRANSFER",sourceId:correction.id},include:{jobs:true}});
  assert.equal(event.jobs.length,1); assert.equal(event.jobs[0].participationId,before.id);
  assert.ok(!JSON.stringify(event).includes(input.reason));
  assert.ok(!JSON.stringify(await db.auditEvent.findMany({where:{action:"PARTICIPATION_TRANSFERRED"}})).includes(input.reason));
});
